#!/usr/bin/env python3
"""
Verification script for BioLabCalc Wiki.
Checks file presence, internal markdown link integrity, and ensures no agent tags or watermarks remain.
"""

import os
import re
import sys

WIKI_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "wiki")

FORBIDDEN_PATTERNS = [
    r"\bgenerated by agent\b",
    r"\bai agent\b",
    r"\bsubagent\b",
    r"\bagent notes\b",
    r"\bagent \d\b",
    r"<!-- generated",
    r"\bco-authored by ai\b",
    r"\bllm signature\b",
    r"\bi am an ai\b",
]

def verify_wiki():
    if not os.path.isdir(WIKI_DIR):
        print(f"Error: Wiki directory not found at {WIKI_DIR}")
        sys.exit(1)

    wiki_files = [f for f in os.listdir(WIKI_DIR) if f.endswith(".md")]
    print(f"[*] Found {len(wiki_files)} wiki markdown files in {WIKI_DIR}:")
    for f in sorted(wiki_files):
        size = os.path.getsize(os.path.join(WIKI_DIR, f))
        print(f"  - {f} ({size:,} bytes)")

    # Page names without .md extension
    page_names = set(os.path.splitext(f)[0] for f in wiki_files)

    errors = []
    warnings = []

    # Check for forbidden agent docstrings / tags
    print("\n[*] Checking for agent docstrings and forbidden tags...")
    for f in sorted(wiki_files):
        filepath = os.path.join(WIKI_DIR, f)
        with open(filepath, "r", encoding="utf-8", errors="replace") as fh:
            content = fh.read()

        for pattern in FORBIDDEN_PATTERNS:
            matches = re.findall(pattern, content, flags=re.IGNORECASE)
            if matches:
                errors.append(f"Forbidden pattern '{pattern}' found in {f} ({len(matches)} occurrences)")

        # Link validation: find [label](Page-Name) with balanced parentheses without catastrophic backtracking
        standard_links = re.findall(r"\[([^\]]+)\]\(([^()#\s]+(?:\([^()#\s]*\)[^()#\s]*)*)(?:#[^)\s]+)?\)", content)
        for label, target in standard_links:
            # Skip external links
            if target.startswith("http://") or target.startswith("https://") or target.startswith("mailto:"):
                continue
            # Remove .md if present
            target_clean = target[:-3] if target.endswith(".md") else target
            if target_clean not in page_names and not os.path.exists(os.path.join(WIKI_DIR, target)):
                warnings.append(f"Broken link in {f}: [{label}]({target}) -> '{target_clean}' does not exist")

    print(f"\n[*] Wiki Audit Results:")
    print(f"  - Total Pages: {len(wiki_files)}")
    print(f"  - Errors: {len(errors)}")
    print(f"  - Link Warnings: {len(warnings)}")

    if errors:
        print("\n[!] Errors found:")
        for err in errors:
            print(f"  - {err}")

    if warnings:
        print("\n[!] Link warnings:")
        for w in warnings:
            print(f"  - {w}")

    if not errors and not warnings:
        print("\n[+] ALL WIKI AUDITS PASSED WITH ZERO ERRORS OR BROKEN LINKS!")
        return 0
    elif not errors:
        print("\n[+] Clean content audit passed! (Some links may point to pages still being written)")
        return 0
    else:
        return 1

if __name__ == "__main__":
    sys.exit(verify_wiki())
